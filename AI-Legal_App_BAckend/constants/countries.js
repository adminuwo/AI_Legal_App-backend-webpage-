/**
 * Resolves country info by name, alias, demonym, or ISO code
 */
export function getCountryByNameOrCode(query = '') {
  if (!query) return null;
  const trimmed = query.trim();
  const upper = trimmed.toUpperCase();
  const lower = trimmed.toLowerCase();

  // Check direct code match
  if (COUNTRY_MAP[upper]) {
    const name = COUNTRY_MAP[upper];
    return {
      name,
      code: upper.length === 2 ? upper : (COUNTRY_NAME_TO_CODE[name.toLowerCase()] || upper),
      currency: COUNTRY_CURRENCIES[name]?.code || 'USD',
      symbol: COUNTRY_CURRENCIES[name]?.symbol || '$',
      flag: COUNTRY_BY_CODE[upper]?.flag || '🌍'
    };
  }

  // Check name match
  const code = COUNTRY_NAME_TO_CODE[lower];
  if (code && COUNTRY_MAP[code]) {
    const name = COUNTRY_MAP[code];
    return {
      name,
      code,
      currency: COUNTRY_CURRENCIES[name]?.code || 'USD',
      symbol: COUNTRY_CURRENCIES[name]?.symbol || '$',
      flag: COUNTRY_BY_CODE[code]?.flag || '🌍'
    };
  }

  // Check demonym match
  const demonymCountry = DEMONYM_MAP[lower];
  if (demonymCountry) {
    const dCode = COUNTRY_NAME_TO_CODE[demonymCountry.toLowerCase()];
    if (dCode) {
      return {
        name: demonymCountry,
        code: dCode,
        currency: COUNTRY_CURRENCIES[demonymCountry]?.code || 'USD',
        symbol: COUNTRY_CURRENCIES[demonymCountry]?.symbol || '$',
        flag: COUNTRY_BY_CODE[dCode]?.flag || '🌍'
      };
    }
  }

  return null;
}
